// Generates design-system/tokens.css (Morning Horizon, light only) from design-system/tokens.json.
// The design-system export ships tokens.json but no tokens.css; this script is the only thing that writes it.
// Run: npm run build:tokens
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const src = path.join(root, 'design-system', 'tokens.json');
const out = path.join(root, 'design-system', 'tokens.css');
const THEME = 'light';

const t = JSON.parse(readFileSync(src, 'utf8'));
const lines = [];
const add = (name, value) => lines.push(`  --${name}: ${value};`);
const pick = (v) => (v && typeof v === 'object' ? v[THEME] : v);

for (const section of ['color', 'spacing', 'radius', 'shadow', 'size', 'opacity']) {
  for (const tok of t[section]?.tokens ?? []) add(tok.name, pick(tok.value));
}

// Typography: families become --font-*, styles become SAP's size parameters.
for (const [k, v] of Object.entries(t.type?.families ?? {})) add(`font-${k}`, v);
for (const group of t.type?.groups ?? []) {
  for (const s of group.styles ?? []) {
    if (s.name === 'objectTitle') add('sapObjectHeader_Title_FontSize', s.fontSize);
    else if (s.name === 'sapFont') add('sapFontSize', s.fontSize);
    else if (/^sapFont(Header\d|Large|Small)$/.test(s.name)) add(`${s.name}Size`, s.fontSize);
  }
}

const css = `/* GENERATED by scripts/build-tokens.mjs from tokens.json (theme: ${THEME}, Morning Horizon). Do not edit. */
:root {
${lines.join('\n')}
}
`;
writeFileSync(out, css);
console.log(`Wrote ${path.relative(root, out)} with ${lines.length} variables.`);
